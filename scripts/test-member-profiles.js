const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const builder = require("./build-store.js");

const ROOT = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(ROOT, file), "utf8");
const guest = read("guest/index.html");
const expectedRoutes = [
  ["customer", "/customer-profile/", "customer-profile/index.html"],
  ["creator", "/creator/", "creator/index.html"],
  ["founding25", "/founding-25-profile/", "founding-25-profile/index.html"],
  ["premiumCreator", "/premium-creator-profile/", "premium-creator-profile/index.html"],
  ["admin", "/admin-profile/", "admin-profile/index.html"],
  ["owner", "/owner-profile/", "owner-profile/index.html"],
];

assert.deepEqual(builder.memberProfileRoutes.map(({ accountClass, route }) => [accountClass, route]),
  expectedRoutes.map(([accountClass, route]) => [accountClass, route]),
  "All six account-class routes are registered with the single Member Profile generator.");

const pages = expectedRoutes.map(([accountClass, route, file]) => {
  const page = read(file);
  const expected = builder.renderMemberProfilePage(guest, {
    canonicalPath: route,
    creatorCatalogRotation: accountClass === "creator",
  });
  assert.equal(page.replace(/\r\n/g, "\n"), expected.replace(/\r\n/g, "\n"),
    `${route} is generated by the shared Member Profile renderer.`);
  assert.match(page, /<title>Member Profile \| Tobacco Road Games<\/title>/);
  assert.match(page, /data-member-profile-page/);
  assert.match(page, /member-profile\.css\?v=member-profile-base1/);
  assert.match(page, /member-profile-library\.js\?v=member-profile-base1/);
  assert.match(page, /member-identity-board\.js\?v=member-identity-board1/);
  assert.match(page, /data-member-identity-board/);
  assert.match(page, /data-member-library-books/g);
  assert.match(page, /upper-cabinet-creator-desktop\.png\?v=creator-title-board3/);
  assert.match(page, /upper-cabinet-creator-tablet\.png\?v=creator-title-board3/);
  assert.match(page, /upper-cabinet-creator-mobile\.png\?v=creator-title-board3/);
  assert.match(page, /the-familiar-framed-poster\.png/);
  assert.doesNotMatch(page, /Creator Dashboard \| Tobacco Road Games|data-creator-library-books|data-creator-identity-page|guest-preview-products\.json/);
  assert.doesNotMatch(page, /data-magical-bookshelf|magical-bookshelf\.js|creator-preview-only|data-creator-preview-only/);
  assert.equal((page.match(/<picture class="shop-wall-cabinet-art"/g) || []).length, 1,
    "The Member Profile contains one shared cabinet component.");
  assert.equal(page.includes("creator-profile-catalog-rotation.js"), accountClass === "creator",
    "Creator's preserved catalog rotation remains Profile-specific.");
  return page;
});

const normalizeProfileMarkup = (page) => page
  .replace(/<link rel="canonical" href="[^"]+">/, "<link rel=canonical>")
  .replace(/<img class="shop-wall-back-wall-art shop-wall-back-wall-art--right creator-dashboard-open-rules-poster" src="\/assets\/the-familiar-framed-poster\.png"[\s\S]*?draggable="false">(?:<img class="shop-wall-back-wall-art shop-wall-back-wall-art--right creator-dashboard-open-rules-poster creator-profile-catalog-cover"[\s\S]*?draggable="false">)?/, "<img class=shared-profile-frame src=/assets/the-familiar-framed-poster.png>")
  .replace(/\s*<script src="\/assets\/js\/creator-profile-catalog-rotation\.js\?v=[^"]+" defer><\/script>/, "");
assert.ok(pages.every((page) => normalizeProfileMarkup(page) === normalizeProfileMarkup(pages[0])),
  "All six Profiles share the same markup, furniture, stylesheets, and identity behavior; only canonical route and Creator rotation differ.");

const memberCss = read("assets/css/member-profile.css");
const dashboardCssCompatibility = read("assets/css/creator-dashboard.css");
assert.match(dashboardCssCompatibility, /@import url\('\/assets\/css\/member-profile\.css'\)/,
  "The existing Dashboard stylesheet delegates to the canonical shared Profile stylesheet.");
assert.match(memberCss, /\.creator-dashboard-identity-overlay[\s\S]*?grid-template-columns: minmax\(0, 1fr\) minmax\(0, 1fr\)/);
assert.match(memberCss, /\.creator-dashboard-identity-overlay[\s\S]*?align-items: start[\s\S]*?column-gap: 0[\s\S]*?transform: translateX\(calc\(-50% - 20px\)\)/,
  "The approved split identity board geometry is retained.");
assert.match(memberCss, /\.creator-dashboard-trg-emblem[\s\S]*?top: -4%[\s\S]*?transform: translateY\(-38px\)[\s\S]*?width: min\(110%, 209px\)/,
  "The approved TRG emblem placement and scale are retained.");
assert.match(memberCss, /\.creator-dashboard-open-rules-poster[\s\S]*?top: calc\(5% - 24px\)[\s\S]*?left: 83\.333%[\s\S]*?height: 90%/,
  "The framed artwork remains in its approved proportional position.");
assert.match(memberCss, /\.creator-dashboard-open-rules-light-cover[\s\S]*?top: 240px[\s\S]*?left: 83\.333%/,
  "The approved framed display light cover remains present.");
assert.match(memberCss, /\.creator-dashboard-creator-initials[\s\S]*?width: min\(227px, 110%\)[\s\S]*?background: linear-gradient/,
  "Metallic gold initials retain their approved rendering.");
assert.match(memberCss, /@media \(max-width: 1023px\)[\s\S]*?\.creator-dashboard-identity-overlay[\s\S]*?width: 91%[\s\S]*?@media \(max-width: 699px\)/,
  "Approved responsive identity-board rules remain covered.");
assert.match(read("styles.css"), /\.guest-open-rules-examination-close[\s\S]*?position: absolute/,
  "Member-owned books continue to use the shared examination controls.");

const creatorArtwork = fs.readFileSync(path.join(ROOT, "assets/images/storefront-shelf-dressing/upper-cabinet-creator-desktop.png"));
const sharedArtwork = fs.readFileSync(path.join(ROOT, "assets/images/storefront-shelf-dressing/upper-cabinet-desktop.png"));
assert.equal(creatorArtwork.readUInt32BE(16), sharedArtwork.readUInt32BE(16), "Creator artwork retains the approved cabinet width.");
assert.equal(creatorArtwork.readUInt32BE(20), sharedArtwork.readUInt32BE(20), "Creator artwork retains the approved cabinet height.");
assert.equal((pages[1].match(/guest-open-rules-row\" aria-hidden=\"true\">\s*<\/div>/g) || []).length, 2,
  "The framed-display bay retains both empty shelf rows without decorative book grids.");
assert.match(pages[1], /class=\"shop-wall-back-wall-art shop-wall-back-wall-art--right creator-dashboard-open-rules-poster\"[^>]+the-familiar-framed-poster\.png/,
  "Creator Profile retains the approved framed artwork.");
assert.match(pages[1], /class=\"creator-dashboard-open-rules-light-overlay\"/);
assert.match(pages[1], /class=\"creator-dashboard-open-rules-light-cover\"/);

const dashboard = read("creator-dashboard/index.html");
assert.match(dashboard, /<title>Creator Dashboard \| Tobacco Road Games<\/title>/,
  "The distinct Dashboard retains its correct title.");
assert.match(dashboard, /creator-dashboard\.js\?v=/,
  "The private Dashboard implementation remains present.");
assert.match(dashboard, /member-identity-board\.js\?v=member-identity-board1/,
  "Dashboard identity reuses the shared component without redesigning its layout.");
assert.doesNotMatch(dashboard, /creator-dashboard-blank\.js/);
assert.match(dashboard, /creator-dashboard-identity-overlay/);
assert.match(dashboard, /creator-dashboard-trg-emblem/);
assert.match(dashboard, /data-member-identity-board/);
assert.match(dashboard, /shop-wall-fixed-cabinet\" data-fixed-cabinet/);
const dashboardRuntime = read("assets/js/creator-dashboard.js");
assert.match(dashboardRuntime, /api\("identity-options"\)/,
  "The existing Dashboard still loads its authorized Creator identity options.");
assert.match(dashboardRuntime, /querySelector\("#creator-name"\)\.textContent/,
  "The Dashboard's existing Creator workspace title remains wired.");
const identityRuntime = read("assets/js/member-identity-board.js");
assert.match(identityRuntime, /fetch\("\/api\/account\/me"/);
assert.match(identityRuntime, /member\?\.displayName/);
assert.match(identityRuntime, /accountClassLabel/);
assert.match(identityRuntime, /buildMetalInitials/);
assert.match(identityRuntime, /window\.addEventListener\("focus"/,
  "Shared member identity refreshes when a page regains focus.");
const generator = read("scripts/build-store.js");
assert.match(generator, /function renderCreatorFurniture\(\)[\s\S]*?renderStorefrontUpperCabinet\(/,
  "The full website generator retains the Dashboard furniture renderer it invokes.");
assert.match(generator, /creatorDashboardTemplate\.replace\([\s\S]*?renderCreatorFurniture\(\)/,
  "The generator call to the Dashboard furniture renderer is resolvable.");

const geography = read("docs/SITE-GEOGRAPHY.md");
for (const [, route] of expectedRoutes) assert.ok(geography.includes(`\`${route}\``), `${route} is documented in site geography.`);
const architecture = read("docs/PAGE-ARCHITECTURE.md");
assert.match(architecture, /Member Profile Base/);
assert.match(architecture, /distinct Dashboard surface/);

console.log("Six Member Profile inheritance tests passed.");
