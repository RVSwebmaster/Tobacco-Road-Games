const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const builder = require("./build-store.js");

const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const normalizeEol = (value) => value.replace(/\r\n/g, "\n");
const normalizeGeneratedWhitespace = (value) => normalizeEol(value).replace(/\n(?:[ \t]*\n)+/g, "\n");
const expectedRoutes = [
  ["customer", "/customer-profile/", "customer-profile/index.html"],
  ["creator", "/creator/", "creator/index.html"],
  ["founding25", "/founding-25-profile/", "founding-25-profile/index.html"],
  ["premiumCreator", "/premium-creator-profile/", "premium-creator-profile/index.html"],
  ["admin", "/admin-profile/", "admin-profile/index.html"],
  ["owner", "/owner-profile/", "owner-profile/index.html"],
];

assert.deepEqual(builder.memberProfileRoutes.map(({ accountClass, route }) => [accountClass, route]),
  expectedRoutes.map(([accountClass, route]) => [accountClass, route]),
  "The six existing account-class routes remain registered.");

const guest = read("guest/index.html");
const pages = expectedRoutes.map(([accountClass, route, file], index) => {
  const page = read(file);
  const expected = builder.renderMemberProfilePage(guest, {
    canonicalPath: route,
    creatorCatalogRotation: accountClass === "creator",
  });
  assert.equal(normalizeGeneratedWhitespace(page), normalizeGeneratedWhitespace(expected), `${route} is generated by the shared Member Profile renderer.`);
  assert.equal(page.includes("creator-profile-catalog-rotation.js"), accountClass === "creator",
    "Creator catalog rotation remains exclusive to the Creator Profile.");
  if (index < 4) {
    assert.match(page, /styles\.css\?v=20261125-profile-plateboard-cache1/,
      `${route} fetches the corrected shared plateboard stylesheet.`);
  }
  return page;
});

const extract = (page, pattern) => page.match(pattern)?.[0] || "";
const customerMain = extract(pages[0], /<main id="member-profile"[\s\S]*?<\/main>/);
const customerPlateboard = extract(customerMain, /<section class="shop-wall-row shop-wall-row--bric-a-brac"[\s\S]*?<\/section>/);
const customerCarousel = extract(customerMain, /<aside class="storefront-ad-marquee"[\s\S]*?<\/aside>/);
const guestMain = builder.renderGuestLandingShopWallMain([]);
const guestPlateboard = extract(guestMain, /<section class="shop-wall-row shop-wall-row--bric-a-brac"[\s\S]*?<\/section>/);
const guestCarousel = extract(guestMain, /<aside class="storefront-ad-marquee"[\s\S]*?<\/aside>/);
const storefrontCss = read("styles.css");
const sharedPlateboardScope = storefrontCss.match(/\.homepage-shop-wall,\s*\.member-profile-shop-wall\s*\{([^}]+)\}/)?.[1] || "";
assert.match(sharedPlateboardScope, /--shop-wall-bric-row-height:\s*148px/,
  "Guest Storefront and Profile pages share the approved plateboard row height.");
assert.match(sharedPlateboardScope, /--shop-wall-bric-surface-height:\s*48px/,
  "Guest Storefront and Profile pages share the approved shelf surface height.");
assert.match(sharedPlateboardScope, /--shop-wall-bric-back-height:\s*100px/,
  "Guest Storefront and Profile pages share the illuminated plaster backing height.");
assert.ok(customerPlateboard, "Customer Profile retains the approved Creator plateboard.");
assert.equal(normalizeEol(customerPlateboard), normalizeEol(guestPlateboard),
  "Customer Profile reuses Guest Storefront plateboard markup.");
assert.ok(customerCarousel, "Customer Profile retains the approved outside advertiser carousel.");
assert.equal(customerCarousel.replace(/\s+/g, " ").trim(), guestCarousel.replace(/\s+/g, " ").trim(),
  "Customer Profile reuses Guest Storefront carousel markup.");

for (const [index, route] of [[1, "/creator/"], [2, "/founding-25-profile/"], [3, "/premium-creator-profile/"]]) {
  const page = pages[index];
  const main = extract(page, /<main id="member-profile"[\s\S]*?<\/main>/);
  const plateboard = extract(main, /<section class="shop-wall-row shop-wall-row--bric-a-brac"[\s\S]*?<\/section>/);
  const carousel = extract(main, /<aside class="storefront-ad-marquee"[\s\S]*?<\/aside>/);
  assert.equal(normalizeEol(plateboard), normalizeEol(customerPlateboard), `${route} reuses the Customer plateboard.`);
  assert.equal(carousel.replace(/\s+/g, " ").trim(), customerCarousel.replace(/\s+/g, " ").trim(),
    `${route} reuses the Customer outside carousel.`);
  assert.ok(main.indexOf("data-fixed-cabinet") < main.indexOf("data-creator-plateboard"), `${route} puts ads beneath Top Shelf.`);
  assert.ok(main.indexOf("data-creator-plateboard") < main.indexOf("class=\"storefront-ad-marquee\""), `${route} puts the outside carousel below Creator ads.`);
  assert.ok(main.indexOf("class=\"storefront-ad-marquee\"") < main.indexOf("data-member-profile-status"), `${route} keeps remaining Profile content below both displays.`);
  assert.match(page, /creator-plateboard\.css\?v=creator-plateboard1/);
  assert.match(page, /creator-plateboard\.js\?v=creator-plateboard1/);
}

for (const [index, page] of pages.slice(4).entries()) {
  assert.doesNotMatch(page, /data-creator-plateboard|creator-plateboard\.(?:js|css)|storefront-ad-marquee/, `${expectedRoutes[index + 4][1]} remains unchanged by advertising displays.`);
}

console.log("Member Profile advertising layout tests passed.");
